-- รัน SQL นี้ใน Supabase Dashboard > SQL Editor
create table if not exists public.item_records (
  id bigint generated by default as identity primary key,
  code text not null,
  item text not null,
  quantity integer not null default 0 check (quantity >= 0),
  note text not null default '',
  created_at timestamptz not null default now()
);

alter table public.item_records enable row level security;

-- นโยบายนี้เปิดให้ผู้ใช้ที่ถือ publishable key อ่าน/เพิ่ม/แก้ไข/ลบได้
-- เหมาะเฉพาะเว็บส่วนตัว/ทดลองที่ยอมรับการเข้าถึงแบบสาธารณะได้
drop policy if exists "Public can read item records" on public.item_records;
create policy "Public can read item records"
on public.item_records for select to anon, authenticated using (true);

drop policy if exists "Public can insert item records" on public.item_records;
create policy "Public can insert item records"
on public.item_records for insert to anon, authenticated with check (true);

drop policy if exists "Public can update item records" on public.item_records;
create policy "Public can update item records"
on public.item_records for update to anon, authenticated using (true) with check (true);

drop policy if exists "Public can delete item records" on public.item_records;
create policy "Public can delete item records"
on public.item_records for delete to anon, authenticated using (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.item_records to anon, authenticated;
grant usage, select on sequence public.item_records_id_seq to anon, authenticated;
